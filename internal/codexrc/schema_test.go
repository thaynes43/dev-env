const schemaDir = "testdata/schema/codex-cli-0.160.1/"

func TestSchemaProvenance(t *testing.T) {
	raw, err := os.ReadFile(schemaDir + "provenance.json")
	if err != nil {
		t.Fatal(err)
	}
	var provenance struct {
		CLIVersion   string            `json:"cliVersion"`
		Files        map[string]string `json:"files"`
		SchemaSHA256 string            `json:"schemaSHA256"`
	}
	if err := json.Unmarshal(raw, &provenance); err != nil {
		t.Fatal(err)
	}
	if provenance.CLIVersion != "codex-cli "+SupportedCLIVersion || len(provenance.Files) != 2 {
		t.Fatal("unexpected CLI/schema pin")
	}
	var manifest strings.Builder
	for _, name := range []string{"ProjectListResponse.json", "RemoteControlStatusReadResponse.json"} {
		raw, err := os.ReadFile(schemaDir + name)
		if err != nil {
			t.Fatal(err)
		}
		hash := sha256.Sum256(raw)
		digest := hex.EncodeToString(hash[:])
		if provenance.Files[name] != digest {
			t.Fatalf("%s differs from generated bytes", name)
		}
		_, _ = fmt.Fprintf(&manifest, "%s  %s\n", digest, name)
	}
	hash := sha256.Sum256([]byte(manifest.String()))
	if provenance.SchemaSHA256 != hex.EncodeToString(hash[:]) {
		t.Fatal("aggregate schema hash mismatch")
	}
}

func TestWireShapesMatchGeneratedSchemas(t *testing.T) {
	for _, tc := range []struct {
		file string
		wire any
	}{
		{"ProjectListResponse.json", projectsResponse{}},
		{"RemoteControlStatusReadResponse.json", statusResponse{}},
	} {
		t.Run(tc.file, func(t *testing.T) {
			raw, err := os.ReadFile(schemaDir + tc.file)
			if err != nil {
				t.Fatal(err)
			}
			var schema map[string]any
			if err := json.Unmarshal(raw, &schema); err != nil {
				t.Fatal(err)
			}
			checkSchemaShape(t, schema, reflect.TypeOf(tc.wire), schema["definitions"].(map[string]any))
			if tc.file == "RemoteControlStatusReadResponse.json" {
				defs := schema["definitions"].(map[string]any)
				status := defs["RemoteControlConnectionStatus"].(map[string]any)
				want := []any{"disabled", "connecting", "connected", "errored"}
				if !reflect.DeepEqual(status["enum"], want) {
					t.Fatal("connection enum changed")
				}
			}
		})
	}
}

// This checks the handwritten wire decoder against the actual generated
// properties, requiredness, nullability, types, nested refs and integer ranges.
// It is not a general-purpose JSON Schema implementation.
func checkSchemaShape(t *testing.T, schema map[string]any, typ reflect.Type, defs map[string]any) {
	t.Helper()
	if ref, ok := schema["$ref"].(string); ok {
		schema = defs[strings.TrimPrefix(ref, "#/definitions/")].(map[string]any)
	}
	nullable := false
	kind, _ := schema["type"].(string)
	if kinds, ok := schema["type"].([]any); ok {
		for _, k := range kinds {
			if k == "null" {
				nullable = true
			} else {
				kind = k.(string)
			}
		}
	}
	if nullable != (typ.Kind() == reflect.Pointer) {
		t.Fatalf("%s nullability differs from generated schema", typ)
	}
	if typ.Kind() == reflect.Pointer {
		typ = typ.Elem()
	}
	switch typ.Kind() {
	case reflect.Struct:
		properties := schema["properties"].(map[string]any)
		if kind != "object" || len(properties) != typ.NumField() {
			t.Fatalf("%s fields differ from generated schema", typ)
		}
		var required []string
		for _, name := range schema["required"].([]any) {
			required = append(required, name.(string))
		}
		var wantRequired []string
		for i := 0; i < typ.NumField(); i++ {
			field := typ.Field(i)
			name, options, _ := strings.Cut(field.Tag.Get("json"), ",")
			property, ok := properties[name].(map[string]any)
			if !ok {
				t.Fatalf("%s absent from generated schema", name)
			}
			if options != "omitempty" {
				wantRequired = append(wantRequired, name)
			}
			checkSchemaShape(t, property, field.Type, defs)
		}
		slices.Sort(required)
		slices.Sort(wantRequired)
		if !slices.Equal(required, wantRequired) {
			t.Fatalf("%s required fields differ from generated schema", typ)
		}
	case reflect.Slice:
		if kind != "array" {
			t.Fatalf("%s is not a generated array", typ)
		}
		checkSchemaShape(t, schema["items"].(map[string]any), typ.Elem(), defs)
	case reflect.Map:
		if kind != "object" {
			t.Fatalf("%s is not a generated map", typ)
		}
		checkSchemaShape(t, schema["additionalProperties"].(map[string]any), typ.Elem(), defs)
	case reflect.Int64:
		if kind != "integer" || schema["format"] != "int64" {
			t.Fatalf("%s does not have the generated integer range", typ)
		}
	case reflect.String:
		if kind != "string" {
			t.Fatalf("%s is not a generated string", typ)
		}
	default:
		t.Fatalf("unhandled fixture shape %s", typ)
	}
}
